CREATE TABLE IF NOT EXISTS admin_user_controls (
 user_id TEXT PRIMARY KEY, suspended INTEGER NOT NULL DEFAULT 0,
 reason TEXT NOT NULL DEFAULT '', updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS admin_photo_controls (
 photo_id TEXT PRIMARY KEY, hidden INTEGER NOT NULL DEFAULT 0,
 reason TEXT NOT NULL DEFAULT '', updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS admin_audit (
 id TEXT PRIMARY KEY, actor TEXT NOT NULL, action TEXT NOT NULL,
 target TEXT NOT NULL, reason TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS admin_audit_created ON admin_audit(created_at);
